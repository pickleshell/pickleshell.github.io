(() => {
  const nomination = document.body.dataset.nomination;
  if (!nomination) return;
  const mean = (v) =>
    Array.isArray(v) && v.length
      ? v.reduce((a, b) => a + b, 0) / v.length
      : null;
  const missing = (v) => v == null;
  const rows = (phase2v2Rows[nomination] || []).map((r, index) => ({
    ...r,
    index,
    f: r.scores?.[0] ?? null,
    r: r.scores?.[1] ?? null,
    m: r.scores?.[2] ?? null,
    s: r.scores?.[3] ?? null,
    overall: mean(r.scores),
  }));
  const order = {
    completed: 0,
    tests_failed: 1,
    forbidden_changes: 2,
    agent_failure: 3,
    unavailable: 4,
  };
  const canonical = (a, b) =>
    (order[a.status] ?? 9) - (order[b.status] ?? 9) ||
    (b.overall ?? -1) - (a.overall ?? -1) ||
    (a.time ?? Infinity) - (b.time ?? Infinity) ||
    a.index - b.index;
  [...rows].sort(canonical).forEach((r, i) => (r.rank = i + 1));
  const esc = (v) =>
    String(v).replace(
      /[&<>'"]/g,
      (c) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          "'": "&#39;",
          '"': "&quot;",
        })[c],
    );
  const score = (v) =>
    missing(v) ? '<span class="na">N/A</span>' : Number(v.toFixed(2));
  const badge = (v) =>
    '<span class="badge result-badge ' +
    v.toLowerCase() +
    '">' +
    v +
    "</span>";
  let key = "overall",
    direction = -1;
  const compare = (a, b) => {
    if (key === "overall" && direction === -1) return canonical(a, b);
    const av = a[key],
      bv = b[key];
    if (missing(av) !== missing(bv)) return missing(av) ? 1 : -1;
    if (missing(av)) return a.index - b.index;
    const d =
      typeof av === "number" ? av - bv : String(av).localeCompare(String(bv));
    return direction * d || a.index - b.index;
  };
  function render() {
    document.getElementById("results-body").innerHTML = [...rows]
      .sort(compare)
      .map((r) => {
        const s = r.scores || [];
        return (
          "<tr><td><strong>#" +
          r.rank +
          '</strong><span class="badge ' +
          (r.status === "completed" ? "success" : "") +
          '">' +
          esc(r.status) +
          '</span></td><td><span class="model">' +
          esc(r.label) +
          '</span><span class="candidate-id">' +
          esc(r.id) +
          '</span></td><td class="score">' +
          badge(r.public) +
          '</td><td class="score">' +
          badge(r.objective) +
          '</td><td class="score">' +
          score(s[0]) +
          '</td><td class="score">' +
          score(s[1]) +
          '</td><td class="score">' +
          score(s[2]) +
          '</td><td class="score">' +
          score(s[3]) +
          '</td><td class="score overall">' +
          score(r.overall) +
          '</td><td class="number">' +
          (missing(r.time) ? "N/A" : r.time.toFixed(3)) +
          '</td><td class="number">' +
          (missing(r.cost) ? "N/A" : "$" + r.cost) +
          "</td><td>" +
          r.channel +
          "</td></tr>"
        );
      })
      .join("");
  }
  document.querySelectorAll("th button").forEach((b) =>
    b.addEventListener("click", () => {
      if (key === b.dataset.key) direction *= -1;
      else {
        key = b.dataset.key;
        direction = 1;
      }
      render();
    }),
  );
  render();
})();
